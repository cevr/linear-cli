// Generates ergo/linear/uploadhost.ergo from the WHATWG host parser the
// original CLI runs (Bun's URL): every code point that host parsing maps into
// the upload host's alphabet, and what it maps to ("" when it is ignored).
// `--check` fails when the checked-in table differs from this runtime's parser.
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const host = "uploads.linear.app";
const alphabet = new Set(host);
const runs = new Map<string, [number, number][]>();
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  // Tab, LF and CR are removed from the whole input before host parsing.
  if (cp === 0x09 || cp === 0x0a || cp === 0x0d) continue;
  const url = URL.parse(`https://x${String.fromCodePoint(cp)}x/`);
  if (!url || !url.hostname.startsWith("x") || !url.hostname.endsWith("x")) continue;
  // A delimiter (/ \ ? # @) ends the host instead of mapping inside it.
  if (url.username || url.password || url.port || url.pathname !== "/" || url.search || url.hash)
    continue;
  const mapped = url.hostname.slice(1, -1);
  if (![...mapped].every((c) => alphabet.has(c))) continue;
  const list = runs.get(mapped) ?? [];
  const last = list.at(-1);
  if (last && last[1] === cp - 1) last[1] = cp;
  else list.push([cp, cp]);
  runs.set(mapped, list);
}
const hex = (n: number) => `0x${n.toString(16)}`;
const lines = [
  "// Code generated by parity/upload-host.ts from WHATWG URL host parsing; DO NOT EDIT.",
  "",
  "// hostRune is what WHATWG host parsing (UTS #46 mapping) makes of c when the",
  "// result can still spell the upload host: a letter of it, a dot, or nothing",
  "// for an ignored code point. Any other code point makes another host.",
  "func hostRune(c rune) Option[string] {",
];
for (const [mapped, list] of [...runs].sort(([a], [b]) => (a < b ? -1 : 1))) {
  const tests = list.map(([a, b]) =>
    a === b ? `c == ${hex(a)}` : `(c >= ${hex(a)} && c <= ${hex(b)})`,
  );
  lines.push(
    `\tif ${tests.join(" || ")} { return Some[string]{Value: ${JSON.stringify(mapped)}} }`,
  );
}
lines.push("\tNone", "}", "");
const text = lines.join("\n");
const path = join(import.meta.dir, "../ergo/linear/uploadhost.ergo");
if (process.argv.includes("--check")) {
  if ((await readFile(path, "utf8")) !== text)
    throw new Error("uploadhost.ergo differs from this runtime's WHATWG host parser; regenerate");
  console.log("ok upload host table matches WHATWG host parsing");
} else {
  await writeFile(path, text);
  console.log(`wrote ${path}`);
}
